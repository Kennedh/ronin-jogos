import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import openapiTS, { astToString } from "openapi-typescript";
import { Ajv2020 } from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { rolldown } from "rolldown";
const root = new URL("../", import.meta.url);
const doc = parse(
  await readFile(new URL("docs/openapi.ronin-runner.v1.yaml", root), "utf8"),
);
const types = astToString(await openapiTS(doc));
const defs = JSON.parse(
  JSON.stringify(doc.components.schemas).replaceAll(
    "#/components/schemas/",
    "#/$defs/",
  ),
);
const runtime =
  "/* Generated from OpenAPI. Do not edit. */\nexport const definitions = " +
  JSON.stringify(defs, null, 2) +
  " as const;\n";
const ajv = new Ajv2020({
  strict: true,
  allErrors: true,
  code: { source: true },
});
addFormats(ajv);
ajv.addSchema({ $id: "urn:ronin:contracts:v1", $defs: defs });
const refs = Object.fromEntries(
  Object.keys(defs).map((name) => [
    name,
    `urn:ronin:contracts:v1#/$defs/${name}`,
  ]),
);
for (const ref of Object.values(refs)) ajv.getSchema(ref);
const compiled = standaloneCode(ajv, refs);
const virtual = fileURLToPath(
  new URL("packages/contracts/src/generated/compiled.cjs", root),
).replaceAll("\\", "/");
const bundle = await rolldown({
  input: "ronin-standalone-entry",
  plugins: [
    {
      name: "ronin-standalone",
      resolveId(id) {
        if (id === "ronin-standalone-entry") return "\0ronin-entry";
        if (id === "ronin-compiled") return virtual;
      },
      load(id) {
        if (id === virtual) return compiled;
        if (id === "\0ronin-entry")
          return 'import validators from "ronin-compiled"; export { validators };';
      },
    },
  ],
});
const result = await bundle.generate({
  format: "esm",
  minify: true,
  comments: false,
});
await bundle.close();
if (
  result.output.length !== 1 ||
  result.output[0].type !== "chunk" ||
  result.output[0].imports.length
)
  throw new Error("standalone_must_be_self_contained");
const outputs = {
  "types.ts": types,
  "schemas.ts": runtime,
  "validators.mjs":
    "/* Generated standalone validators. Do not edit. */\n" +
    result.output[0].code,
  "validators.d.mts":
    "/* Generated. Do not edit. */\nexport const validators: Record<string, (data: unknown) => boolean>;\n",
};
const dir = new URL("packages/contracts/src/generated/", root);
await mkdir(dir, { recursive: true });
for (const [name, content] of Object.entries(outputs)) {
  const path = new URL(name, dir);
  // Use formatter for reproducible generated bytes too.
  const { format } = await import("prettier");
  const expected = await format(content, {
    parser: name.endsWith(".mjs") ? "babel" : "typescript",
  });
  if (process.argv.includes("--check")) {
    if ((await readFile(path, "utf8")) !== expected)
      throw new Error("Stale generated contract: " + fileURLToPath(path));
  } else await writeFile(path, expected);
}
console.log("OpenAPI types and runtime schemas match");
